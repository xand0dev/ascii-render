export type Lang = 'en' | 'uk';
export const LANGS: { id: Lang; short: string; name: string }[] = [
  { id: 'en', short: 'EN', name: 'English' },
  { id: 'uk', short: 'УКР', name: 'Українська' },
];

const DICTS: Record<Lang, Record<Key, string>> = { en, uk };
const LANG_KEY = 'ascii-render-lang';

function detect(): Lang {
  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (fromUrl === 'en' || fromUrl === 'uk') return fromUrl;
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'en' || saved === 'uk') return saved;
  } catch { /* storage unavailable */ }
  return navigator.languages?.some((l) => l.toLowerCase().startsWith('uk')) ? 'uk' : 'en';
}

let current: Lang = detect();

export const lang = () => current;

export function setLang(l: Lang) {
  current = l;
  try { localStorage.setItem(LANG_KEY, l); } catch { /* ignore */ }
  document.documentElement.lang = l;
}

/** Translate a key, filling {placeholders}. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = DICTS[current][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Lookup for keys built at runtime (preset ids, glyph-set ids…), with a fallback when there is no entry. */
export function tryT(key: string, fallback: string): string {
  return key in en ? t(key as Key) : fallback;
}

/** Apply translations to static markup. */
export function translateDom(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n as Key); });
  root.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml as Key); });
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle as Key); });
  root.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder as Key); });
  root.querySelectorAll<HTMLImageElement>('[data-i18n-alt]').forEach((el) => { el.alt = t(el.dataset.i18nAlt as Key); });
  document.documentElement.lang = current;
}
